def load(pg, n):
    return Image.open(os.path.join(SRC, f'x-{pg:03d}-{n:03d}.png')).convert('RGB')

def trim_black(im, pad=0.06, thr=26):
    g = ImageOps.grayscale(im).point(lambda v: 255 if v > thr else 0)
    bb = g.getbbox()
    if not bb: return im
    l, t, r, b = bb
    pw, ph = int((r - l) * pad), int((b - t) * pad)
    return im.crop((max(0, l - pw), max(0, t - ph), min(im.width, r + pw), min(im.height, b + ph)))

manifest = {}
total = 0
for slug, items in PICKS.items():
    d = os.path.join(OUT, slug); os.makedirs(d, exist_ok=True)
    for name, (pg, n, o) in items.items():
        im = load(pg, n)
        if o.get('crop'): im = trim_black(im)
        maxw = o.get('maxw', 1400)
        if im.width > maxw:
            im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
        path = os.path.join(d, name + '.jpg')
        im.save(path, 'JPEG', quality=84, optimize=True, progressive=True)
        total += os.path.getsize(path)
        manifest[f'{slug}/{name}'] = dict(src=f'/work/{slug}/{name}.jpg', w=im.width, h=im.height)

